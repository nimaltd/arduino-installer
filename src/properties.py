"""
library.properties: how a library in the libraries folder introduces itself to Arduino.

The Arduino IDE and arduino-cli read it for the library's name, version and
the boards it runs on, and show it in Library Manager's list of what is
installed. A library written for any project has none, so it is written here,
from installer.yml, into the library's folder, and written again on every
install and update.

A library made for Arduino ships its own, which knows the library better than
this does, and is left alone. Its first line tells the two apart: this one
starts with a comment, which Arduino skips.
"""

import re
from pathlib import Path, PurePosixPath

from .core.target import ALREADY, CHANGED, MANUAL, Outcome

NAME = "library.properties"

MARK = "# Generated by arduino-installer"

# Arduino's own categories, the only ones Library Manager takes.
CATEGORIES = (
    "Display", "Communication", "Signal Input/Output", "Sensors", "Device Control",
    "Timing", "Data Storage", "Data Processing", "Other",
)

# installer.yml's category, as the nearest of Arduino's.
FROM_CATEGORY = {
    "sensor": "Sensors",
    "storage": "Data Storage",
    "display": "Display",
    "communication": "Communication",
    "wireless": "Communication",
    "timing": "Timing",
    "power": "Device Control",
    "input": "Signal Input/Output",
    "math": "Data Processing",
}

_OWNER = re.compile(r"github\.com[/:]([^/\s]+)/", re.IGNORECASE)


def _label(library):
    return f"{library.name} {library.version}".strip()


def author(library):
    """The author: as installer.yml gives it, or the owner of the repository it comes from."""
    if library.arduino.author:
        return library.arduino.author

    found = _OWNER.search(library.repository or "")

    return found.group(1) if found else "Unknown"


def category(library):
    """Arduino's category for the library: as given, or the nearest to its own category."""
    return library.arduino.category or FROM_CATEGORY.get(library.category, "Other")


def includes(library):
    """The header a sketch includes, the way the include folder makes it."""
    if not library.headers:
        return None

    landed = PurePosixPath(library.headers[0].destination)

    for folder in sorted(library.include_dirs, key=len, reverse=True):
        if folder in (".", ""):
            continue

        try:
            return landed.relative_to(folder).as_posix()
        except ValueError:
            continue

    return landed.as_posix()


def one_line(text):
    """A value for one line of the file: no line breaks."""
    return " ".join(str(text).split())


def properties(library):
    """The text of library.properties for this library."""
    name = author(library)
    lines = [
        f"{MARK} for {_label(library)}. Written again on",
        "# every install and update, so a change made here does not last.",
        f"name={library.name}",
    ]

    if library.version:
        lines.append(f"version={library.version}")

    lines += [
        f"author={one_line(name)}",
        f"maintainer={one_line(library.arduino.maintainer or name)}",
        f"sentence={one_line(library.description or library.name)}",
        "paragraph=",
        f"category={category(library)}",
        f"url={one_line(library.repository or '')}",
        f"architectures={','.join(library.arduino.architectures)}",
    ]

    if library.arduino.depends:
        lines.append(f"depends={','.join(library.arduino.depends)}")

    header = includes(library)

    if header:
        lines.append(f"includes={header}")

    return "\n".join(lines) + "\n"


def _ours(path):
    try:
        return path.read_text(encoding="utf-8").startswith(MARK)
    except (OSError, UnicodeDecodeError):
        return False


def ships_its_own(destination):
    """Whether the library brought a library.properties of its own."""
    path = Path(destination) / NAME

    return path.is_file() and not _ours(path)


def write(library, destination):
    """Write library.properties, only when it changed. Returns an Outcome."""
    path = Path(destination) / NAME

    if ships_its_own(destination):
        return Outcome(NAME, ALREADY, f"{library.name} has its own library.properties, used as it is.")

    data = properties(library).encode("utf-8")

    try:
        if path.is_file() and path.read_bytes() == data:
            return Outcome(NAME, ALREADY, f"{library.name}'s library.properties is up to date.")

        path.write_bytes(data)
    except OSError as error:
        return Outcome(NAME, MANUAL, f"Could not write {path}: {error}")

    return Outcome(NAME, CHANGED, f"Wrote {library.name}'s library.properties, which Arduino knows it by.")


def remove(destination):
    """Delete the library.properties write() made. One of the library's own is not touched."""
    path = Path(destination) / NAME

    if path.is_file() and _ours(path):
        try:
            path.unlink()
        except OSError:
            pass
